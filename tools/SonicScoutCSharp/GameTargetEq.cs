using System.Globalization;
using System.IO;
using System.Net.Http;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace SonicScout;

internal static class GameTargetEq
{
    // AutoEq's own solver compensates the measured headphone against the custom
    // target, including smoothing, boost limits and headroom. Do not add a raw
    // target curve to an already compensated Harman profile.
    public static async Task<string> GenerateAsync(HttpClient client, string name, string filterUrl, string target)
    {
        if (!Uri.TryCreate(filterUrl, UriKind.Absolute, out Uri? uri))
            throw new InvalidDataException("Choose an AutoEq measured profile to calculate this game target.");
        string[] path = Uri.UnescapeDataString(uri.AbsolutePath).Split('/');
        int results = Array.IndexOf(path, "results");
        if (uri.Host != "raw.githubusercontent.com" || results < 0 || results + 2 >= path.Length)
            throw new InvalidDataException("This profile has no supported headphone measurement for a game target.");
        string source = path[results + 1];
        string category = path[results + 2];
        using JsonDocument outer = JsonDocument.Parse(await client.GetStringAsync("https://autoeq.app/entries"));
        using JsonDocument catalog = JsonDocument.Parse(outer.RootElement.ValueKind == JsonValueKind.String
            ? outer.RootElement.GetString()! : outer.RootElement.GetRawText());
        if (!catalog.RootElement.TryGetProperty(name, out JsonElement entries))
            throw new InvalidDataException("A headphone measurement for this game target is unavailable. Choose another measured profile.");
        JsonElement[] candidates = (entries.ValueKind == JsonValueKind.Array ? entries.EnumerateArray().ToArray() : new[] { entries })
            .Where(entry => entry.GetProperty("source").GetString() == source).ToArray();
        string Normalize(string value) => Regex.Replace(value.ToLowerInvariant(), "[^a-z0-9]", "");
        JsonElement[] matched = candidates.Where(entry => Normalize(category).StartsWith(Normalize(entry.GetProperty("rig").GetString()!))).ToArray();
        JsonElement choice = matched.Length == 1 ? matched[0] : candidates.Length == 1 ? candidates[0]
            : throw new InvalidDataException("The measurement rig is ambiguous. Choose another profile for this game target.");
        string request = BuildRequest(name, source, choice.GetProperty("rig").GetString()!, target);
        using HttpResponseMessage response = await client.PostAsync("https://autoeq.app/equalize", new StringContent(request, Encoding.UTF8, "application/json"));
        response.EnsureSuccessStatusCode();
        using JsonDocument result = JsonDocument.Parse(await response.Content.ReadAsStringAsync());
        string correction = result.RootElement.GetProperty("graphic_eq").GetString() ?? string.Empty;
        ValidateCorrection(correction);
        return "# SonicScout game target: measured headphone compensation generated by AutoEq\n" + correction + "\n";
    }

    internal static string BuildRequest(string name, string source, string rig, string target)
    {
        List<double> frequencies = new(), gains = new();
        foreach (string line in target.Split('\n'))
        {
            string[] cells = line.Trim().Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries);
            if (cells.Length < 2 || !double.TryParse(cells[0], NumberStyles.Float, CultureInfo.InvariantCulture, out double frequency)) continue;
            if (!double.TryParse(cells[1], NumberStyles.Float, CultureInfo.InvariantCulture, out double gain) ||
                !double.IsFinite(frequency) || !double.IsFinite(gain) || frequency < 10 || frequency > 24000 ||
                Math.Abs(gain) > 150 || (frequencies.Count > 0 && frequency <= frequencies[^1]))
                throw new InvalidDataException("The bundled game target has invalid frequency data.");
            frequencies.Add(frequency); gains.Add(gain);
        }
        if (frequencies.Count < 10 || frequencies[0] > 30 || frequencies[^1] < 10000)
            throw new InvalidDataException("The bundled game target does not cover the audible frequency range.");
        return JsonSerializer.Serialize(new {
            name, source, rig, target = new { frequency = frequencies, raw = gains },
            graphic_eq = true, parametric_eq = false, fixed_band_eq = false, convolution_eq = false,
            bass_boost_gain = 0, treble_boost_gain = 0, tilt = 0,
            response = new { fr_fields = new[] { "frequency" }, base64fp16 = false }
        });
    }

    internal static void ValidateCorrection(string correction)
    {
        if (!correction.StartsWith("GraphicEQ: ") || correction.Contains('\n') || correction.Contains('\r'))
            throw new InvalidDataException("The target service returned an invalid EQ response.");
        double previous = 0; int count = 0;
        foreach (string pair in correction[11..].Split(';'))
        {
            string[] cells = pair.Trim().Split(' ', StringSplitOptions.RemoveEmptyEntries);
            if (cells.Length != 2 || !double.TryParse(cells[0], NumberStyles.Float, CultureInfo.InvariantCulture, out double frequency) ||
                !double.TryParse(cells[1], NumberStyles.Float, CultureInfo.InvariantCulture, out double gain) ||
                !double.IsFinite(frequency) || !double.IsFinite(gain) || frequency <= previous || frequency > 24000 || gain > 0 || gain < -150)
                throw new InvalidDataException("The target response is malformed or lacks clipping headroom.");
            previous = frequency; count++;
        }
        if (count < 10) throw new InvalidDataException("The target response contains too few EQ bands.");
    }
}
